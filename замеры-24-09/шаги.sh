#!/bin/zsh
# Круг 24 сентября — часть в ШАГАХ: фаза 1 и отдельные замеры круга 21-го.
#
# Зачем круг. 24-го убрана вторая стартовая точка. До этого загрузчик
# сажал одного инженера в дальнем городе, если там набиралась группа
# заявок: на юго-востоке это была Кашира, и участок выезжал из двух мест
# вместо одного. Разрешения на такое допущение не было — цитата, которой
# оно оправдывалось, не нашлась ни в стенограмме сессии вопросов, ни в
# отчёте, ни в переписке, а на прямой вопрос «верно ли брать адрес офиса
# как старт для всех инженеров региона?» постановщик ответил, что у
# каждого региона свой офис и своя точка старта (стенограмма 16 сентября,
# 00:07:54). Вдобавок список `ДОПУЩЕНИЯ` всё это время утверждал, что
# стартовая точка взята из выгрузки как есть.
#
# По правилу 6 перегенерируется всё, где есть юго-восток, то есть всё.
# Восток и югоцентр выезжали из одной точки и раньше: их дни не
# изменились ни на байт, и в этом круге они обязаны повторить круг
# 22-го вечера до цифры. Разошлись — это находка, а не шум.
#
# Ждать сдвига: юго-восток. Проба на восьми зёрнах до круга дала
# назначено −0,62 ± 0,43, выполнено −0,41 ± 0,26, км +82 ± 73;
# исполнителей столько же. Сеть участка сменилась с `6f1247f0387c`
# (74 узла, с каширской точкой) на `00a8e0ae22dd` (73 узла) — матрица
# лежала в репозитории с 15 сентября, ломаные вырезаны из прежней сети с
# перенумерацией узлов, расхождение матриц 0,1 с и 2,9 м на округлении.
#
# Бюджет в шагах: сон приостановит, но не испортит, батарея допустима,
# параллельная нагрузка только замедляет. Запускать из отдельной копии
# репозитория на закоммиченном состоянии: правки движка в рабочей копии во
# время круга в него не попадут.
#
# Имена переменных латиницей: zsh не берёт кириллицу в идентификаторах.
cd "$(dirname "$0")/.."
SRC="замеры-16-09"
OUT="замеры-24-09"
export PYTHONPATH=.

START=$(date '+%F %T')
echo "шаги начаты: $START"
echo "питание: $(pmset -g batt | head -1)"
echo "отпечаток кода: $(python3 -c 'from vrptw.server import отпечаток_кода; print(отпечаток_кода())')"
echo "коммит: $(git rev-parse --short HEAD)"

run() {
  local name="$1"; shift
  echo "═══ $name   [$(date '+%T')]"
  if python3 -u "$@" > "$OUT/$name.txt" 2>&1; then
    echo "    готово $name [$(date '+%T')]"
  else
    echo "    УПАЛО $name [$(date '+%T')] — хвост:"
    tail -6 "$OUT/$name.txt" | sed 's/^/      /'
  fi
}

echo "───── фаза 1, по два ─────"
run "база-против-нас"  "$SRC/база-против-нас.py" &
run "кого-переобучать" "$SRC/кого-переобучать.py" &
wait

ORDER=$(python3 "$SRC/порядок.py" "$OUT/кого-переобучать.txt")
echo "$ORDER" > "$OUT/порядок.txt"
echo "порядок кандидатов: $ORDER"
TOP2=$(echo "$ORDER" | cut -d, -f1-2)
echo "двое лучших: $TOP2"

run "кривая-переобучения"   "$SRC/кривая-переобучения.py" "$ORDER" &
run "обучить-против-нанять" "$SRC/обучить-против-нанять.py" &
wait
run "разрыв-смены" "$SRC/разрыв-смены.py" &
run "перенос-окон" "$SRC/перенос-окон.py" &
wait
run "дефицит-после" "$SRC/дефицит-после.py" "$ORDER" &
run "кто-не-влез"   "$SRC/кто-не-влез.py" &
wait
run "физпредел-зон" "$SRC/физпредел-зон.py" &
run "окна-спрос"    "$SRC/окна-спрос.py" &
wait
run "обязательства-на-зонах"     "$SRC/на-зонах.py" обязательства &
run "равномерность-против-людей" "$SRC/равномерность-против-людей.py" &
wait
run "дешёвая-рекомендация" "$SRC/дешёвая-рекомендация.py" "$TOP2" &
run "буфер-и-баланс"       "замеры-20-09/буфер-и-баланс.py" &
wait

echo "───── отдельные замеры круга 21-го, по два ─────"
run "база-против-нас-интервалы" "$OUT/база-против-нас-интервалы.py" &
run "приоритет"                 "$OUT/приоритет.py" &
wait
run "сколько-людей"       "$OUT/сколько-людей.py" &
run "рекомендация-честно" "$OUT/рекомендация-честно.py" &
wait

echo "───── сон за время шагов (для протокола; на шаги не влияет) ─────"
SLEPT=$(pmset -g log | awk -v s="$START" '$1" "$2 >= s' | grep -cE " Sleep  ")
echo "записей Sleep с $START: $SLEPT"
echo "шаги закончены: $(date '+%F %T')"
