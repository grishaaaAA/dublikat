def _контрольные_не_читаются(корень: Path | None = None) -> tuple[list[str], int]:
    """Контрольные выгрузки не попадают ни в один путь исполнения.

    Правило 12 держалось на чтении кода, а раздел 6 ФТ обещал проверку.
    Вот она, тремя вопросами:

    * загрузчик знает ровно три файла заявок — `REGIONS`;
    * никто не обходит каталог заявок маской: иначе новый файл рядом
      подхватился бы молча, и «мы их не читаем» держалось бы на том, что
      никто не положил лишнего;
    * имена посторонних файлов из этого каталога не встречаются в
      исходниках движка.

    «Посторонний» считается от `REGIONS`, а не по слову «контроль»:
    так же поймается любой другой файл, который окажется рядом.

    Второе число — сколько посторонних файлов лежит в каталоге. **Ноль —
    это не провал, а лучшее из состояний**: в публичном снимке
    контрольных выгрузок нет вовсе, и первые две проверки продолжают
    работать. Выяснилось на самом снимке: сторож требовал, чтобы
    посторонние файлы нашлись, и падал ровно там, где их правильно нет.
    """
    from .core.load import ORDERS_DIR, REGIONS

    плохо: list[str] = []
    if len(REGIONS) != 3:
        плохо.append(f"загрузчик знает {len(REGIONS)} зон, а их три")
    известные = {Path(п).name for п in REGIONS.values()}
    посторонние = sorted(p.name for p in ORDERS_DIR.iterdir()
                         if p.is_file() and p.name not in известные)

    корень = корень or Path(__file__).resolve().parent.parent
    # Сам сторож каталог обходит — на то он и сторож; его не считаем.
    свой = Path(__file__).name
    for путь in sorted(корень.rglob("*.py")):
        if "__pycache__" in путь.parts or путь.name == свой:
            continue
        текст = путь.read_text(encoding="utf-8")
        for обход in ("ORDERS_DIR.glob", "ORDERS_DIR.rglob",
                      "ORDERS_DIR.iterdir", "ORDERS_DIR.walk"):
            if обход in текст:
                плохо.append(f"{путь.name}: {обход} — каталог заявок обходится "
                             f"маской, лишний файл подхватится молча")
        for имя in посторонние:
            if имя in текст:
                плохо.append(f"{путь.name}: упомянут {имя}")
    return плохо, len(посторонние)


def _порог_приоритета(корень: Path | None = None) -> tuple[list[str], int]:
    """Документы обязаны называть то число, которое даёт `PRIORITY_WEIGHTS`.

    Ступени приоритета разведены весами, а не отдельными уровнями
    сравнения: при 1 : 100 : 10 000 одна авария дороже 99 подключений, но
    не дороже ста. До 23 сентября README, ФТ и `CLAUDE.md` обещали «хуже
    любого числа» — на зонах (56, 66 и 83 заявки) разницы нет, а в чужой
    выгрузке со ста с лишним подключениями обещание перестаёт быть
    правдой.

    Здесь число считается из самих весов и сверяется с документами
    наружу: поменяются веса — проверка потребует поправить и слова.
    Возвращает (нарушения, порог).
    """
    from .solvers.improved import PRIORITY_WEIGHTS

    пороги = {int(старший // младший) - 1
              for младший, старший in zip(PRIORITY_WEIGHTS, PRIORITY_WEIGHTS[1:])
              if младший}
    корень = корень or Path(__file__).resolve().parent.parent
    плохо: list[str] = []
    if len(пороги) != 1:
        плохо.append(f"ступени разведены неодинаково: пороги {sorted(пороги)} — "
                     f"одним числом это уже не описать")
        return плохо, 0
    порог = пороги.pop()

    # Обещание «хуже любого числа» весами не обеспечивается никогда.
    запрещено = ("любого числа нераспределённых", "любое число нераспределённых",
                 "любого числа ремонтов")
    for имя in _ДОКУМЕНТЫ_НАРУЖУ:
        путь = корень / имя
        if not путь.is_file():
            continue
        текст = путь.read_text(encoding="utf-8")
        низ = текст.lower()
        for фраза in запрещено:
            if фраза in низ:
                плохо.append(f"{имя}: «{фраза}» — весами это не держится")
        # Где про приоритет говорят, там обязаны назвать порог — и
        # именно рядом с фразой, а не где-нибудь в файле. Раньше стояло
        # `str(порог) not in текст`, то есть искалось вхождение цифр по
        # всему документу: при весах (1, 7, 49) порог равен 6, документ
        # по-прежнему говорил «99», а сторож молчал — цифра «6» в тексте
        # где-нибудь да найдётся.
        рядом = re.findall(r"(\d+)\s+нераспределённых", текст)
        if рядом and any(int(ч) != порог for ч in рядом):
            плохо.append(f"{имя}: сказано «{рядом[0]} нераспределённых», "
                         f"а веса дают порог {порог}")
        if "приоритет" in низ and "нераспределённая авария" in низ \
                and not рядом:
            плохо.append(f"{имя}: про приоритет сказано, а порог {порог} "
                         f"не назван")
    return плохо, порог


