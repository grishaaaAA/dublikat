def _блок_офиса(office_text: str | None) -> int:
    """С какого имени начинается бригада этого офиса.

    Ключ — **адрес офиса**, а не имя зоны, и это не придирка: выгрузка
    `восток.csv`, загруженная кнопкой, обязана дать тот же день, что
    зона «восток» (`собрать_день`), а `ident` у неё свой. Офис же у них
    один и тот же, и блок имён выходит один и тот же.

    Адреса не переписаны сюда руками: они читаются из тех же файлов
    зон — копия данных в коде разошлась бы с данными молча.
    """
    if not office_text:
        return 3 * БЛОК_ИМЁН
    return _офисы_зон().get(office_text.strip(), 3 * БЛОК_ИМЁН)


@lru_cache(maxsize=1)
def _офисы_зон() -> dict[str, int]:
    офисы = {}
    for номер, зона in enumerate(REGIONS):
        try:
            _строки, офис = read_orders_csv(REGIONS[зона])
        except (OSError, ValueError):
            continue
        if офис:
            офисы[офис.strip()] = номер * БЛОК_ИМЁН
    return офисы


def build_engineers(n: int, office: dict, сдвиг: int = 0) -> list[Engineer]:
    """Инженеры зоны: все выезжают из офиса, смены веером до 22:00.

    Стартовая точка **одна на зону** — адрес офиса, который приходит
    последней строкой файла. Постановщику задали этот вопрос прямо, и он
    ответил прямо (`передача-17-09/стенограмма-16-09.txt`, 00:07:25:
    «Стартовая точка у каждого региона или офиса своя, или все бригады
    стартуют из одной точки? И если у каждого своя, то верно ли брать
    адрес офиса в последней строке файла как старт для всех инженеров
    региона?» — 00:07:54: «Это для каждого региона свой офис и,
    соответственно, своя точка старта»).

    Второй точки здесь быть не должно, и это стоит прочесть, прежде чем
    заводить её снова. До 24 сентября модуль сажал одного человека в
    дальнем городе, если там набиралась группа заявок: на юго-востоке
    это была Кашира, и инженеров на участке становилось две группы —
    тринадцать от офиса и один оттуда. Оправдывалось это цитатой о
    «бригадах, обслуживающих удалённые города Подмосковья», которой нет
    ни в стенограмме, ни в отчёте, ни в переписке — владелец подтвердил,
    что разрешения не было. Допущение стоило 0,6 назначенного визита и
    82 км на участке, но держалось ни на чём и вдобавок противоречило
    списку `ДОПУЩЕНИЯ`, где стартовая точка значится взятой из выгрузки
    как есть. Сторож `selfcheck._одна_точка_выезда` теперь это стережёт.
    """
    out: list[Engineer] = []
    for i in range(n):
        skills, transport, start, end = БРИГАДЫ[i % len(БРИГАДЫ)]
        out.append(Engineer(
            id=f"E{i:02d}",
            name=ИМЕНА[(сдвиг + i) % len(ИМЕНА)],
            skills=set(skills),
            grade=2,
            home_node=-1,
            home_lat=office["lat"],
            home_lon=office["lon"],
            home_address=office.get("address"),
            shift_start=start,
            shift_end=end,
            speed=1.0,
            transport=transport,
        ))
    return out


def load_day(region: str, n_engineers: int = 14, date: str = "2026-08-17",
             quiet: bool = False) -> Day:
    """
    Собрать `Day` по зоне обслуживания.

    Сеть строится под координаты именно этого дня — приклеивать настоящий
    дом к ближайшему из наших шестисот синтетических означало бы ошибаться
    на километр в каждом перегоне и в обеих обязательных метриках.
    """
    from . import geocode
    from .osm import network_for_points

    region = region.lower().strip()
    if region not in REGIONS:
        raise ValueError(f"зона «{region}» неизвестна; есть: "
                         f"{', '.join(REGIONS)}")

    rows, office_text = read_orders_csv(REGIONS[region])
    if not office_text:
        raise ValueError(f"в файле зоны «{region}» нет адреса офиса — "
                         f"без стартовой точки план строить нельзя")

    texts = [r["address"] for r in rows if r["address"]] + [office_text]
    geo = geocode.geocode_all(texts, quiet=quiet)
    if not quiet:
        print(f"  адреса: {geocode.report(geo)}")

    # Кэш сети кладём в отдельный каталог, а не рядом с прочими
    # матрицами: общий шаблон `.gitignore` исключает матрицы под
    # «чужие наборы точек», а зоны заказчика — не чужой набор, это и
    # есть данные демонстрации. Без них на защите понадобился бы
    # интернет, а обещано обратное.
    return собрать_день(
        rows, office_text, geo, n_engineers=n_engineers, date=date,
        ident=region, quiet=quiet,
        сеть=lambda points: network_for_points(points, quiet=quiet,
                                               cache_dir=DATA_DIR / "сети"))


def собрать_день(rows: list[dict], office_text: str, geo: dict, *,
                 n_engineers: int, date: str, ident: str, сеть,
                 quiet: bool = False) -> Day:
    """
    `Day` из разобранных строк выгрузки: заявки, бригада, сеть, проверка.

    Общая часть зоны заказчика и выгрузки, которую принёс диспетчер: день
    из файла `восток.csv`, загруженного кнопкой, обязан выйти тем же, что
    зона «восток», — иначе два пути к одним данным давали бы два плана.
    Откуда брать сеть, решает зовущий (`сеть` — функция от точек): зоны
    строят её под свои адреса и кладут в репозиторий, выгрузка берёт
    готовую или строит в каталоге состояния.
    """
    office_point = geo.get(office_text) or {}
    if not office_point.get("lat"):
        raise ValueError(f"офис «{office_text}» не геокодирован — "
                         f"инженерам неоткуда выезжать")

    orders, skipped = build_orders(rows, geo)
    if skipped and not quiet:
        print(f"  пропущено заявок: {len(skipped)}")
        for s in skipped[:5]:
            print(f"    {s['id']}: {s['почему']} — {s['address']}")

    engineers = build_engineers(n_engineers, {
        "lat": office_point["lat"], "lon": office_point["lon"],
        "address": office_text,
    }, сдвиг=_блок_офиса(office_text))

    # Сеть: точки заявок и офис. Больше стартовых точек в дне нет — вся
    # бригада выезжает из офиса зоны (см. `build_engineers`).
    points = [{"lat": o.lat, "lon": o.lon, "district": o.district}
              for o in orders]
    points.append({"lat": office_point["lat"], "lon": office_point["lon"],
                   "district": "офис"})
    net = сеть(points)

    for o in orders:
        o.node = net.nearest_node(o.lat, o.lon)
    office_node = net.nearest_node(office_point["lat"], office_point["lon"])
    for e in engineers:
        e.home_node = office_node

    day = Day(date=date, orders=orders, engineers=engineers, network=net,
              hard_end=HARD_END, ident=ident)

    # Проверка дня писалась ровно под этот момент: «генератор заменится на
    # загрузчик, и молчаливо неверный `Day` не упадёт — он спланируется и
    # даст покрытие 30% и полдня разбирательств». Но подключена она была
    # только к `selfcheck` и `scalebench`, то есть к синтетике, а на пути
    # настоящих данных не звалась ни разу. Стоит она 0 мс.
    #
    # Поломка — это отказ: день, которым планировщик подавится, лучше не
    # отдавать вовсе, чем отдать вместе с объяснением, почему алгоритм
    # «вдруг стал хуже». Предупреждения печатаются, потому что они про
    # странность, а не про непригодность.
    from .validate_day import check as _проверить_день
    поломки, предупреждения = _проверить_день(day)
    if поломки:
        raise ValueError(
            f"день «{ident}» не годен к планированию:\n  "
            + "\n  ".join(поломки))
    if предупреждения and not quiet:
        for строка in предупреждения:
            print(f"  ! {строка}")

    return day


