def main(argv: list[str]) -> int:
    if argv and argv[0] in ("допущения", "assumptions"):
        print(ДОПУЩЕНИЯ)
        return 0

    region = argv[0] if argv else "восток"
    if region in ("все", "all"):
        regions = list(REGIONS)
    else:
        regions = [region]

    for name in regions:
        print(f"\n══ зона «{name}» ══")
        day = load_day(name)
        skills = {}
        transports = {}
        for o in day.orders:
            skills[o.skill] = skills.get(o.skill, 0) + 1
        for e in day.engineers:
            transports[e.transport] = transports.get(e.transport, 0) + 1
        work = sum(o.est_minutes for o in day.orders)
        shift = sum(e.shift_end - e.shift_start for e in day.engineers)
        print(f"  заявок {len(day.orders)}, инженеров {len(day.engineers)}")
        print(f"  навыки: " + ", ".join(
            f"{SKILL_TITLES[k].lower()} {v}" for k, v in sorted(skills.items())))
        print(f"  транспорт: " + ", ".join(
            f"{TRANSPORT[k]['title'].lower()} {v}"
            for k, v in sorted(transports.items())))
        req = sum(1 for o in day.orders if o.requires_transport)
        print(f"  заявок с требованием по транспорту: {req}")
        print(f"  работы {work / 60:.1f} ч при {shift / 60:.1f} ч смен "
              f"(без учёта дороги)")
        окна = sorted({(o.window_start, o.window_end) for o in day.orders})
        print(f"  окон различных: {len(окна)}, "
              f"самое позднее закрывается в {max(w[1] for w in окна) // 60}:"
              f"{max(w[1] for w in окна) % 60:02d}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
