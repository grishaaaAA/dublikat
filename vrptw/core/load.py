def _minutes(stamp: str) -> int | None:
    """«17.08.2026 10:00» → 600 минут от полуночи."""
    m = re.search(r"(\d{1,2}):(\d{2})\s*$", stamp.strip())
    if not m:
        return None
    return int(m.group(1)) * 60 + int(m.group(2))


def read_orders_csv(path: Path) -> tuple[list[dict], str | None]:
    """
    Прочитать выгрузку. Возвращает строки заявок и адрес офиса.

    Адрес офиса лежит не в отдельном файле и не в шапке, а последней
    строкой после двух пустых, в колонке «Тип заявки BK», с подписью
    «Адрес офиса» в колонке номера. Выглядит как порча файла, но это не
    она: это стартовая точка инженеров, которую ТЗ требует обязательно.
    """
    text = Path(path).read_bytes().decode(ENCODING)
    rows = list(csv.DictReader(io.StringIO(text), delimiter=DELIMITER))

    orders: list[dict] = []
    office: str | None = None

    for row in rows:
        num = (row.get("Заявка") or "").strip()
        if not num:
            continue
        if num.lower().startswith("адрес оф"):
            office = (row.get("Тип заявки BK") or "").strip() or None
            continue
        orders.append({
            "id": num,
            "bk": (row.get("Тип заявки BK") or "").strip(),
            "hd": (row.get("Тип заявки HD") or "").strip(),
            "start": (row.get("Начало") or "").strip(),
            "end": (row.get("Окончание") or "").strip(),
            "district": (row.get("Район") or "").strip(),
            "address": (row.get("Адрес") or "").strip(),
            "gigabit": (row.get("Гигабитное подключение") or "").strip(),
        })

    return orders, office


# --- выгрузка, которую принёс диспетчер --------------------------------
#
# Три зоны лежат в репозитории и читаются `read_orders_csv` как есть: они
# проверены глазами и замерены. Файл, загруженный кнопкой, — другое дело:
# его видят впервые, и каждую строку, которую нельзя спланировать, надо
# назвать с причиной, а не уронить весь день и не спланировать молча
# мусор. Отсюда отдельный, строгий разбор. Формат тот же: колонки
# выгрузки, «;», время с датой, «Адрес офиса» последней строкой.

КОЛОНКИ = ("Заявка", "Тип заявки BK", "Тип заявки HD", "Начало", "Окончание",
           "Район", "Адрес")
КОЛОНКИ_НУЖНЫ = ("Заявка", "Тип заявки BK", "Начало", "Окончание", "Адрес")

_МОМЕНТ = re.compile(r"^\s*(\d{1,2})\.(\d{1,2})\.(\d{4})\s+(\d{1,2}):(\d{2})(?::\d{2})?\s*$")


def _момент(stamp: str) -> tuple[str, int] | None:
    """«17.08.2026 10:00» → («2026-08-17», 600). Не разобралось — None."""
    import datetime

    m = _МОМЕНТ.match(stamp or "")
    if not m:
        return None
    д, мес, г, ч, мин = map(int, m.groups())
    try:
        дата = datetime.date(г, мес, д)
    except ValueError:
        return None
    if ч > 23 or мин > 59:
        return None
    return дата.isoformat(), ч * 60 + мин


def _прочесть_текст(data: bytes) -> tuple[str, str]:
    """Байты файла → текст и имя кодировки.

    Выгрузка приходит в cp1251, но пересохранённая в редакторе — уже в
    UTF-8, часто с меткой BOM. Сначала пробуем UTF-8 строго: текст в cp1251
    почти никогда не бывает правильным UTF-8, а наоборот — бывает всегда
    (cp1251 «прочтёт» любые байты кракозябрами)."""
    if data[:4] == b"PK\x03\x04":
        raise ValueError("это файл Excel (.xlsx), а не CSV: откройте его в Excel "
                         "и сохраните как «CSV (разделители — точка с запятой)»")
    if data.startswith(b"\xef\xbb\xbf"):
        return data[3:].decode("utf-8", errors="replace"), "UTF-8"
    try:
        return data.decode("utf-8"), "UTF-8"
    except UnicodeDecodeError:
        pass
    try:
        return data.decode(ENCODING), ENCODING
    except UnicodeDecodeError:
        raise ValueError("файл не читается ни как UTF-8, ни как cp1251 — "
                         "это не текстовая выгрузка")


def разобрать_выгрузку(data: bytes) -> dict:
    """
    Разобрать выгрузку дня, принесённую диспетчером.

    Возвращает строки заявок в том же виде, что `read_orders_csv`, адрес
    офиса, дату дня и два списка: отложенные строки (с номером строки в
    файле и причиной) и предупреждения. Отказ — ValueError со словами,
    что не так и что сделать: такой файл не посчитать вовсе.

    Отложенная строка — та, которую нельзя спланировать: без адреса, с
    неразобранным временем, с пустым окном, с чужой датой. День при этом
    считается без неё: одна кривая строка не должна отнимать остальные
    восемьдесят.
    """
    if not data or not data.strip():
        raise ValueError("файл пустой")
    текст, кодировка = _прочесть_текст(data)
    строки_текста = текст.splitlines()
    шапка = next((с for с in строки_текста if с.strip()), "")
    разделитель = max((";", ",", "\t"), key=шапка.count)
    if not шапка.count(разделитель):
        разделитель = DELIMITER

    reader = csv.DictReader(io.StringIO(текст), delimiter=разделитель)
    колонки = [(к or "").strip() for к in (reader.fieldnames or [])]
    reader.fieldnames = колонки
    нет = [к for к in КОЛОНКИ_НУЖНЫ if к not in колонки]
    if нет:
        raise ValueError(
            "в файле нет колонок " + ", ".join(f"«{к}»" for к in нет)
            + ". Нужна выгрузка дня в формате заказчика: «"
            + ";".join(КОЛОНКИ) + "»")

    rows: list[dict] = []
    отложены: list[dict] = []
    office: str | None = None
    даты: dict[str, int] = {}
    моменты: list[tuple] = []

    def отложить(line: int, num: str, причина: str) -> None:
        отложены.append({"line": line, "id": num, "reason": причина})

    for row in reader:
        line = reader.line_num
        get = lambda к: (row.get(к) or "").strip()  # noqa: E731
        num = get("Заявка")
        if not num:
            # Пустые строки перед адресом офиса — часть формата. Строка с
            # данными, но без номера, — нет: её не отличить от соседней.
            if any(get(к) for к in колонки if к != "Заявка"):
                отложить(line, "", "нет номера заявки")
            continue
        if num.lower().startswith("адрес оф"):
            office = get("Тип заявки BK") or None
            continue
        rec = {
            "id": num,
            "bk": get("Тип заявки BK"),
            "hd": get("Тип заявки HD"),
            "start": get("Начало"),
            "end": get("Окончание"),
            "district": get("Район"),
            "address": get("Адрес"),
            "gigabit": get("Гигабитное подключение"),
        }
        if not rec["address"]:
            отложить(line, num, "нет адреса")
            continue
        нач, кон = _момент(rec["start"]), _момент(rec["end"])
        if нач is None or кон is None:
            плохое = rec["start"] if нач is None else rec["end"]
            отложить(line, num, f"время не разобрано: «{плохое}», нужно «17.08.2026 10:00»")
            continue
        даты[нач[0]] = даты.get(нач[0], 0) + 1
        моменты.append((line, rec, нач, кон))

    if office is None:
        raise ValueError(
            "в файле нет строки «Адрес офиса» — инженерам неоткуда выезжать. "
            "В выгрузке она стоит последней: «Адрес Офиса;<адрес>»")
    if not моменты:
        raise ValueError("в файле не нашлось ни одной заявки, которую можно "
                         "спланировать" + (f": {отложены[0]['reason']}" if отложены else ""))

    # День выгрузки — дата, на которую приходится больше всего заявок. Заявка
    # на другой день в этот план не ляжет: у того дня свои смены.
    день = max(sorted(даты), key=lambda д: даты[д])
    неопознаны = 0
    строки_файла: list[int] = []
    for line, rec, нач, кон in моменты:
        if нач[0] != день:
            отложить(line, rec["id"], f"другой день: {_дата_по_русски(нач[0])}, "
                                      f"а выгрузка за {_дата_по_русски(день)}")
            continue
        # Окончание на следующий день — «до конца смены», а не пустое окно.
        if кон[0] > нач[0]:
            rec = {**rec, "end": f"{_дата_по_русски(день)} 23:59"}
        ws, we = _window(rec)
        if we <= ws:
            # Пустое само по себе или стало пустым, когда его зажали в
            # рабочий день: причина у этих двух разная, и совет тоже.
            пусто_само = кон[0] == нач[0] and кон[1] <= нач[1]
            отложить(line, rec["id"],
                     f"окно приёма пустое: {rec['start']} – {rec['end']}" if пусто_само
                     else f"окно приёма {rec['start'][-5:]}–{rec['end'][-5:]} вне рабочего "
                          f"дня {DAY_START // 60:02d}:00–{HARD_END // 60:02d}:00")
            continue
        if (rec["bk"].lower() not in НОРМАТИВ_BK
                and rec["hd"].lower() not in HD_TO_CODE):
            неопознаны += 1
        rows.append(rec)
        строки_файла.append(line)

    предупреждения: list[str] = []
    if неопознаны:
        предупреждения.append(
            f"тип заявки не опознан у {неопознаны} стр.: навык и длительность "
            "взяты как у локальной заявки")
    повторы = len(rows) - len({r["id"] for r in rows})
    if повторы:
        предупреждения.append(
            f"номера повторяются у {повторы} стр.: к повторным добавлен суффикс «-2»")
    if not rows:
        raise ValueError("в файле не нашлось ни одной заявки, которую можно "
                         "спланировать: " + отложены[0]["reason"])

    return {"rows": rows, "lines": строки_файла, "office": office, "date": день,
            "encoding": кодировка, "delimiter": разделитель,
            "skipped": sorted(отложены, key=lambda s: s["line"]),
            "warnings": предупреждения}


def _дата_по_русски(iso: str) -> str:
    г, м, д = iso.split("-")
    return f"{д}.{м}.{г}"


# Норматив организаторов (прислан 16 сентября). Четыре строки таблицы
# ложатся на справочник «Тип заявки BK» один в один — и класть его надо
# именно на BK, а не на код работ: один и тот же тип HD стоит в выгрузке
# под разными BK. «Конвергенция абонента» — 75 раз под «Подключением» и
# 2 раза под «Дозаказом», «Заказ подключения/Дозаказ оборудования» — 11 и
# 3. По коду работ их не различить, по BK — различить можно.
#
# В «Базовый норматив» входит дорога (20 мин), а у нас она считается
# отдельно по настоящей дорожной сети. Поэтому берётся сумма «технические
# работы + документы» — это время У КЛИЕНТА, ровно то, что означает
# `est_minutes`. Взять базовый норматив целиком значило бы учесть дорогу
# дважды.
#
# Сверка, которая это подтверждает: средний перегон в наших планах
# 15–19 минут по зонам, норматив закладывает 20 — тот же порядок.
НОРМАТИВ_BK: dict[str, int] = {
    "подключение": 60 + 10,          # Подключение клиентов Базовая — 90 с дорогой
    "дозаказ": 10 + 10,              # Дозаказ оборудования — 40 с дорогой
    "локальная заявка": 30 + 0,      # Локальная заявка/ремонт — 50 с дорогой
    "глобальная проблема": 80 + 0,   # Аварий на ТКД — 100 с дорогой
}


def _минут_по_нормативу(row: dict, work) -> int:
    """Длительность работ у клиента.

    Из норматива заказчика, если BK опознан; иначе — наша оценка по типу
    работ. Разброс длительности, доступ в подъезд и вероятность неявки в
    нормативе не заданы и остаются нашими.
    """
    return НОРМАТИВ_BK.get(row["bk"].strip().lower(), work.est_minutes)


# Приоритет при нехватке ресурсов: «Авария → Подключение → Ремонт /
# Дозаказ», авария имеет максимальный.
#
# Источник — обратная связь организаторов, присланная 20 сентября, уже
# после сессии вопросов (пятнадцать пунктов,
# `передача-20-09/СОСТОЯНИЕ.md`). Владелец это подтвердил 25 сентября.
#
# Оговорка, которую надо знать: **текста этой обратной связи на диске
# нет**, есть только наш пересказ. В стенограмме 16 сентября порядка
# тоже нет — там на прямой вопрос отвечено «в данной задаче приоритет
# заявки не задавался» (00:14:49), и это не противоречие, а просто более
# ранняя точка: порядок прислали позже. Особый статус аварии в
# стенограмме уже был («в случае аварии может» вытеснять обычные визиты,
# 00:16:23).
#
# Если текст обратной связи найдётся — положить в `источники/`, рядом с
# выпиской из ТЗ. Ровно так 25 сентября закрылся такой же вопрос по
# базовому варианту: полночи доказывали то, что читается за минуту.
#
# Берётся из «Типа заявки BK», а не из кода работ, по той же причине, что
# и норматив: организаторы классифицируют именно по BK, и их три ступени
# ложатся на его четыре значения один в один. По коду работ разложить
# нельзя — «Заказ подключения/Дозаказ оборудования» стоит в выгрузке и
# под «Подключением», и под «Дозаказом», то есть один код работ попадает
# в разные ступени.
ПРИОРИТЕТ_BK: dict[str, int] = {
    "глобальная проблема": 2,   # авария — максимальный
    "подключение": 1,           # подключение — второй
    "дозаказ": 0,               # дозаказ — вместе с ремонтом
    "локальная заявка": 0,      # ремонт
}


def _приоритет(row: dict) -> int:
    """Ступень приоритета заявки. Незнакомый BK — низшая, без домысла."""
    return ПРИОРИТЕТ_BK.get(row["bk"].strip().lower(), 0)


def _code_for(row: dict) -> str:
    code = HD_TO_CODE.get(row["hd"].lower())
    if code:
        return code
    return BK_FALLBACK.get(row["bk"].lower(), "нет_линка")


def _window(row: dict) -> tuple[int, int]:
    """
    Окно визита, зажатое в рабочие сутки.

    Часть заявок приходит с окном 0:01–23:59 — это «когда угодно», а не
    ночная работа. Такие зажимаем в рабочий день целиком; в остальных
    случаях окно берётся как есть.
    """
    ws, we = _minutes(row["start"]), _minutes(row["end"])
    if ws is None or we is None:
        return DAY_START, HARD_END
    if ws <= 1 and we >= 23 * 60 + 58:
        return DAY_START, HARD_END
    return max(ws, DAY_START), min(we, HARD_END)


def адрес_для_показа(текст: str | None) -> str | None:
    """«г.Город Москва, …» → «Город Москва, …», как у остальных адресов.

    Выгрузка дублирует город у девяти адресов (восемь на востоке, один на
    югоцентре), и экран писал «г.Город Москва». Правится только показ:
    геокодер ищет по исходной строке выгрузки, она — ключ его кэша, и
    координата берётся по ней раньше, чем заявка получит этот текст."""
    if not текст:
        return текст
    return re.sub(r"^г\.\s*(?=Город\s)", "", текст, flags=re.I)


def build_orders(rows: list[dict], geo: dict) -> tuple[list[Order], list[dict]]:
    """
    Собрать заявки. Возвращает годные и список пропущенных с причиной.

    Пропускаем только то, что нельзя спланировать физически: заявку без
    координаты. Тихо подставлять центр района нельзя — ошибка в километр
    попала бы в обе обязательные метрики сразу.
    """
    orders: list[Order] = []
    skipped: list[dict] = []
    seen: set[str] = set()

    for row in rows:
        point = geo.get(row["address"]) or {}
        if not point.get("lat"):
            skipped.append({**row, "почему": "адрес не геокодирован"})
            continue

        # Номера в выгрузке изредка повторяются. Планировщику нужен
        # уникальный ключ, а диспетчеру — исходный номер: держим оба.
        oid = row["id"]
        if oid in seen:
            suffix = 2
            while f"{oid}-{suffix}" in seen:
                suffix += 1
            oid = f"{oid}-{suffix}"
        seen.add(oid)

        code = _code_for(row)
        work = REAL_WORK_TYPES[code]
        ws, we = _window(row)

        orders.append(Order(
            id=oid,
            work_type=code,
            district=row["district"] or "—",
            lat=point["lat"],
            lon=point["lon"],
            node=-1,                     # проставится, когда встанет сеть
            address=адрес_для_показа(row["address"]),
            window_start=ws,
            window_end=we,
            # В этих данных обязательство перед абонентом — само окно:
            # срока по SLA в выгрузке нет, и придумывать его неоткуда.
            sla_deadline=we,
            priority=_приоритет(row),
            est_minutes=_минут_по_нормативу(row, work),
            requires_transport=TRANSPORT_REQUIRED.get(code),
            hard_end=HARD_END,
            # В выгрузке оборудования нет — состав выводится из вида работ,
            # см. `domain.EQUIPMENT`.
            equipment=equipment_for(oid, code),
        ))

    return orders, skipped


