"""
Совместимость с Windows: блокировка файла и вывод в консоль.

Решение смотрят на машинах проверяющих, и Windows среди них вероятна. Там
у движка было две беды, обе воспроизводятся на Mac:

* `fcntl` на Windows нет — `import vrptw.server` падал на первой строке
  блокировки архива (воспроизводит `sys.modules['fcntl'] = None`);
* кодировка по умолчанию — cp1251: всё, что читалось `read_text()` без
  кодировки, ломалось на кириллице готовых планов и сетей
  (воспроизводит `LC_ALL=ru_RU.CP1251`). Это лечится явной
  `encoding="utf-8"` у каждого чтения и записи, сторож — в selfcheck;
  а вывод в консоль, где кодировка не своя, — здесь.
"""

from __future__ import annotations

import sys
import time

try:
    import fcntl
except ImportError:                     # Windows
    fcntl = None
try:
    import msvcrt
except ImportError:                     # всё, кроме Windows
    msvcrt = None


# Сколько всего ждать занятый файл, прежде чем писать без замка.
ЗАМОК_ВСЕГО = 60.0
# `LK_LOCK` сам стоит в очереди около десяти секунд и только потом
# отказывает. Отказ заметно быстрее — это не очередь, а «здесь так
# нельзя»: закрытый дескриптор, сетевая папка, плейсхолдер OneDrive,
# файловая система без блокировок. Ждать такого нечего.
ЗАМОК_ОЧЕРЕДЬ = 1.0
# Пауза между попытками — на случай, если постоянный отказ окажется
# медленнее порога: без паузы круг съедает ядро.
ЗАМОК_ПАУЗА = 0.05

_сказано_про_замок = False


def _без_замка(причина: str) -> None:
    """Сказать один раз за запуск, что дальше пишем без блокировки.

    Один раз — потому что архив пишется на каждое действие диспетчера, и
    строка на каждое превратила бы вывод в стену. Молчать нельзя: без
    замка две программы, пишущие разом, испортят архив, и человек должен
    знать, что такая возможность открылась.
    """
    global _сказано_про_замок
    if not _сказано_про_замок:
        _сказано_про_замок = True
        print(f"  замок файла здесь не ставится ({причина}); пишу без него — "
              f"архив испортится, только если писать из двух программ разом",
              file=sys.stderr)


def запереть(f) -> bool:
    """Исключительная блокировка открытого файла; ждёт, пока освободится.

    Возвращает, взят ли замок на самом деле: `отпереть` снимает только
    взятое.

    На Windows — `msvcrt.locking` на первый байт. `LK_LOCK` пробует
    десять раз по секунде и только потом отказывает, поэтому занятый файл
    ждём по кругу. Но отказать он может и мгновенно — на закрытом
    дескрипторе, в сетевой папке, на плейсхолдере OneDrive, на файловой
    системе без блокировок. До 23 сентября здесь стоял `while True …
    except OSError: continue` без счётчика и без паузы: при таком отказе
    поток молча съедал ядро до убийства процесса — 13 млн попыток за три
    секунды. Вставало это на первой же записи архива, то есть на кнопке
    «Создать расчёт» у проверяющего.

    Поэтому быстрый отказ считаем за «здесь так нельзя» и пишем без
    замка, сказав об этом вслух; очередь ждём, но не дольше
    `ЗАМОК_ВСЕГО`. Писать без замка — сознательный выбор, он тут был и
    раньше: архив пишут редко, и лучше писать без замка, чем повиснуть
    или не запуститься вовсе.
    """
    if fcntl is not None:
        fcntl.flock(f, fcntl.LOCK_EX)
        return True
    if msvcrt is None:
        # Ни POSIX, ни Windows — такого почти не бывает, но молчать здесь
        # нельзя по той же причине, что и ниже: без замка две программы,
        # пишущие разом, испортят архив, и человек должен об этом знать.
        # Прежде эта ветка возвращала False молча, и `_без_замка` рядом
        # обещала вслух то, чего одна из трёх дорог не делала.
        _без_замка("ни fcntl, ни msvcrt")
        return False
    f.seek(0)
    срок = time.monotonic() + ЗАМОК_ВСЕГО
    while True:
        начало = time.monotonic()
        try:
            msvcrt.locking(f.fileno(), msvcrt.LK_LOCK, 1)
            return True
        except OSError as ошибка:
            if time.monotonic() - начало < ЗАМОК_ОЧЕРЕДЬ:
                _без_замка(f"{type(ошибка).__name__}: {ошибка}")
                return False
            if time.monotonic() >= срок:
                _без_замка(f"занят дольше {ЗАМОК_ВСЕГО:.0f} с")
                return False
            time.sleep(ЗАМОК_ПАУЗА)


def отпереть(f, заперт: bool = True) -> None:
    """Снять блокировку. `заперт=False` — её не брали, снимать нечего:
    `msvcrt.locking(LK_UNLCK)` на незапертом байте сам отказал бы
    ошибкой, и падало бы уже на выходе из `with`."""
    if not заперт:
        return
    if fcntl is not None:
        fcntl.flock(f, fcntl.LOCK_UN)
    elif msvcrt is not None:
        f.seek(0)
        try:
            msvcrt.locking(f.fileno(), msvcrt.LK_UNLCK, 1)
        except OSError:
            # Снятие замка на Windows умеет отказать: система сняла его
            # сама, сетевая папка, плейсхолдер OneDrive. Зовут нас из
            # `finally` (`state._замок`), и брошенная отсюда ошибка
            # **подменила бы собой исходную** — или превратила удачную
            # запись архива в отказ. Замок к этому времени либо снят,
            # либо уйдёт с закрытием файла.
            pass


# Чем заменять знаки, которых нет в кодовой странице. Замена подобрана
# так, чтобы отметки оставались различимы глазом и грепом: «+» и «x»
# читаются как «прошло» и «упало», а `errors="replace"` превращал их все
# в одинаковый «?» — и посчитать отметки в перенаправленном выводе было
# нельзя. Проверяющего мы просим их считать, значит они обязаны дожить
# до файла.
ЗАМЕНЫ = {
    "✓": "+",
    "✗": "x",
    "═": "=",
    "─": "-",
    "→": "->",
    "←": "<-",
    "★": "*",
}


class _Переводчик:
    """Обёртка над потоком: заменяет знаки, которых нет в его кодировке.

    Не трогает то, что кодировка берёт: в cp1251 есть «…», «±», «·» и
    тире — их портить незачем. Подменяются только те, что иначе стали бы
    «?».
    """

    def __init__(self, поток, замены: dict[str, str]):
        self._поток = поток
        self._замены = замены

    def write(self, текст: str) -> int:
        for знак, замена in self._замены.items():
            текст = текст.replace(знак, замена)
        return self._поток.write(текст)

    def __getattr__(self, имя):
        return getattr(self._поток, имя)


def _непереводимые(поток) -> dict[str, str]:
    """Какие из наших знаков эта кодировка не возьмёт."""
    кодировка = getattr(поток, "encoding", None)
    if not кодировка:
        return {}
    нельзя = {}
    for знак, замена in ЗАМЕНЫ.items():
        try:
            знак.encode(кодировка)
        except (UnicodeEncodeError, LookupError):
            нельзя[знак] = замена
    return нельзя


def консоль() -> None:
    """Вывод не падает на знаках, которых нет в кодировке консоли, —
    и остаётся читаемым.

    В окно консоли Windows Python пишет сам, в обход кодовой страницы; но
    вывод, перенаправленный в файл, идёт в cp1251 — а в ней нет «✓» и
    «═», которыми говорят проверки, и `check > log.txt` падал бы посреди
    прогона.

    Двух бед здесь две. Падение лечит `errors="replace"`, и это стояло
    тут с самого начала. Но замена превращает **все** незнакомые знаки в
    одинаковый «?», и в перенаправленном выводе «✓» и «✗» становятся
    неразличимы — а мы просим проверяющего посчитать отметки и сказать,
    были ли «✗». Поэтому сперва переводим свои знаки в те, что кодировка
    берёт: «+», «x», «=». Проверено подстановкой cp1251 здесь, на Mac;
    на Windows живьём не проверялось.
    """
    for имя in ("stdout", "stderr"):
        поток = getattr(sys, имя, None)
        if поток is None:
            continue
        try:
            if (поток.encoding or "").lower().replace("-", "") == "utf8":
                continue
            поток.reconfigure(errors="replace")
        except (AttributeError, ValueError):
            pass
        замены = _непереводимые(поток)
        if замены:
            setattr(sys, имя, _Переводчик(поток, замены))


# --- подмена и удаление файлов ----------------------------------------
#
# На POSIX `rename` и `unlink` безразличны к тому, что файл кто-то держит
# открытым. На Windows — нет: CPython открывает файлы без
# `FILE_SHARE_DELETE`, и `MoveFileExW`/`DeleteFileW` по такому файлу
# отказывают `PermissionError` (WinError 5 и 32). Держать его может кто
# угодно: соседний поток сервера, замер из терминала, а на Windows ещё и
# антивирус с индексатором — они берут хэндл на только что созданный файл
# на доли секунды.
#
# Цена промаха видна человеку. Подготовка выгрузки, отработавшая минуту,
# не доходит до «готова» и молча остаётся «принята»; «Создать расчёт»
# отвечает пятисоткой; удаление выгрузки — тоже.
#
# Поэтому короткий круг повторов. Он ничего не меняет на POSIX: там
# первая же попытка проходит.
ПОДМЕНА_ПОПЫТОК = 10
ПОДМЕНА_ПАУЗА = 0.05


def подменить(откуда, куда) -> None:
    """`os.replace` с повторами на отказ занятости."""
    import os
    for попытка in range(ПОДМЕНА_ПОПЫТОК):
        try:
            os.replace(откуда, куда)
            return
        except PermissionError:
            if попытка == ПОДМЕНА_ПОПЫТОК - 1:
                raise
            time.sleep(ПОДМЕНА_ПАУЗА)


def убрать(путь, *, дерево: bool = False) -> None:
    """Удалить файл или каталог, переждав того, кто держит его открытым.

    `missing_ok`/`ignore_errors` здесь не годятся: первое глотает только
    «нет такого файла», второе — вообще всё, включая настоящий отказ.
    """
    import shutil
    for попытка in range(ПОДМЕНА_ПОПЫТОК):
        try:
            if дерево:
                shutil.rmtree(путь)
            else:
                путь.unlink()
            return
        except FileNotFoundError:
            return
        except PermissionError:
            if попытка == ПОДМЕНА_ПОПЫТОК - 1:
                raise
            time.sleep(ПОДМЕНА_ПАУЗА)
